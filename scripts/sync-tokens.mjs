/**
 * Project src/app/globals.css token values into design-system/tokens/.
 * Source of truth: `:root` and `.dark` custom properties, plus the
 * non-inline `@theme` block (fonts, tracking, radius scale, shadow).
 * Re-running writes the same bytes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "src/app/globals.css");
const outDir = path.join(root, "design-system/tokens");

const HSL = /^(-?\d+(?:\.\d+)?)\s+(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%$/;

const FONT_SANS = '"Geist", "Geist Sans", ui-sans-serif, system-ui, sans-serif';
const FONT_MONO =
  '"Geist Mono", ui-monospace, "SF Mono", Menlo, Monaco, Consolas, monospace';

const css = stripComments(readFileSync(sourcePath, "utf8"));
const light = new Map();
const dark = new Map();
const theme = new Map();

for (const rule of rulesIn(css)) {
  const selector = rule.selector.replace(/\s+/g, " ").trim();
  if (selector === ":root") {
    for (const [name, value] of declarations(rule.body)) light.set(name, value);
  } else if (selector === ".dark") {
    for (const [name, value] of declarations(rule.body)) dark.set(name, value);
  } else if (selector === "@theme") {
    for (const [name, value] of declarations(rule.body)) theme.set(name, value);
  }
}

for (const name of ["--background", "--foreground", "--primary", "--border", "--input", "--ring", "--radius"]) {
  if (!light.has(name)) throw new Error(`globals.css :root is missing ${name}`);
}
for (const name of ["--background", "--primary", "--border", "--input", "--ring"]) {
  if (!dark.has(name)) throw new Error(`globals.css .dark is missing ${name}`);
}

const colors = [...light.keys()].filter((name) => HSL.test(light.get(name)));
for (const name of colors) {
  if (!HSL.test(dark.get(name) ?? "")) {
    throw new Error(`globals.css .dark is missing an HSL value for ${name}`);
  }
}

const generated = "Generated by scripts/sync-tokens.mjs from src/app/globals.css. Do not edit.";

write("channels.css", channelsCss());
write("tokens.css", tokensCss());
write("tokens.json", `${JSON.stringify(tokensJson(), null, 2)}\n`);
write("index.css", '@import "./tokens.css";\n');
write("studio-theme.css", studioThemeCss());

function channelsCss() {
  return `/* ${generated} */\n:root {\n${block(light)}\n}\n\n.dark {\n${block(dark)}\n}\n`;
}

function tokensCss() {
  const shared = sharedTokens();
  return `/* ${generated}
   Hex colors are the sRGB projection of the site HSL channels.
   --brand-primary is --primary. Fonts are the site Geist stacks
   with families a sibling app can load without next/font. */\n:root {\n${cssDecls([...shared, ...colorDecls("light")])}\n}\n\n.dark {\n${cssDecls([...shared, ...colorDecls("dark")])}\n}\n`;
}

function studioThemeCss() {
  const base = [
    ["--font-sans", FONT_SANS],
    ["--font-mono", FONT_MONO],
    ...[...theme.keys()]
      .filter((name) => name.startsWith("--tracking-"))
      .map((name) => [name, theme.get(name)]),
    ["--radius", light.get("--radius")],
    ...["--radius-lg", "--radius-md", "--radius-sm"]
      .filter((name) => theme.has(name))
      .map((name) => [name, theme.get(name)]),
    ...(theme.has("--shadow-subtle")
      ? [["--shadow-subtle", theme.get("--shadow-subtle")]]
      : []),
    ...(light.has("--ease-out-quart")
      ? [["--ease-out-quart", light.get("--ease-out-quart")]]
      : []),
    ...colors.map((name) => [`--color-${name.slice(2)}`, `hsl(${light.get(name)})`]),
  ];
  const darkColors = colors.map((name) => [
    `--color-${name.slice(2)}`,
    `hsl(${dark.get(name)})`,
  ]);
  return `/* ${generated}
   Design Studio theme. Scope a prototype with class "robcrock-theme".
   Dark values follow the site's .dark class and Studio's data-color-mode. */\n.robcrock-theme {\n${cssDecls(base)}\n}\n\n.robcrock-theme.dark,\n.dark .robcrock-theme,\n.robcrock-theme[data-color-mode="dark"] {\n${cssDecls(darkColors)}\n}\n`;
}

function tokensJson() {
  const semantic = {};
  for (const name of colors) {
    const bare = name.slice(2);
    if (bare.endsWith("-foreground")) continue;
    const foreground = `${bare}-foreground`;
    if (light.has(`--${foreground}`)) {
      semantic[bare] = {
        "@": colorValue(bare, true),
        foreground: colorValue(foreground, false),
      };
    } else {
      semantic[bare] = colorValue(bare, false);
    }
  }
  semantic.brand = {
    primary: {
      $description: `Alias of --primary (${light.get("--primary")} / dark ${dark.get("--primary")}).`,
      ...colorValue("primary", false),
    },
  };

  return {
    $description: generated,
    primitives: {
      ease: {
        out: {
          quart: {
            $type: "cubicBezier",
            $value: light.get("--ease-out-quart"),
          },
        },
      },
      radius: {
        $type: "dimension",
        $value: light.get("--radius"),
      },
      tracking: Object.fromEntries(
        [...theme.keys()]
          .filter((name) => name.startsWith("--tracking-"))
          .map((name) => [
            name.slice("--tracking-".length),
            { $type: "dimension", $value: theme.get(name) },
          ]),
      ),
      font: {
        family: {
          sans: { $type: "fontFamily", $value: "Geist" },
          mono: { $type: "fontFamily", $value: "Geist Mono" },
        },
      },
      shadow: {
        subtle: { $type: "shadow", $value: theme.get("--shadow-subtle") },
      },
    },
    semantic,
  };
}

function colorValue(bare, leaf) {
  const lightHex = hex(light.get(`--${bare}`));
  const darkHex = hex(dark.get(`--${bare}`));
  return {
    $type: "color",
    $value: lightHex,
    $extensions: {
      "figma-console-mcp": {
        ...(leaf ? { leafRemap: true } : {}),
        modes: { Dark: darkHex },
        primaryMode: "Light",
      },
    },
  };
}

function sharedTokens() {
  const rows = [];
  if (light.has("--ease-out-quart")) rows.push(["--ease-out-quart", light.get("--ease-out-quart")]);
  if (light.has("--radius")) rows.push(["--radius", light.get("--radius")]);
  for (const name of theme.keys()) {
    if (name.startsWith("--tracking-")) rows.push([name, theme.get(name)]);
  }
  rows.push(["--font-family-sans", FONT_SANS]);
  rows.push(["--font-family-mono", FONT_MONO]);
  if (theme.has("--shadow-subtle")) rows.push(["--shadow-subtle", theme.get("--shadow-subtle")]);
  return rows;
}

function colorDecls(mode) {
  const source = mode === "light" ? light : dark;
  const rows = colors.map((name) => [name, hex(source.get(name))]);
  rows.push(["--brand-primary", hex(source.get("--primary"))]);
  return rows;
}

function block(map) {
  return cssDecls([...map.entries()]);
}

function cssDecls(entries) {
  return entries.map(([name, value]) => `  ${name}: ${value};`).join("\n");
}

function hex(value) {
  const match = HSL.exec(value);
  if (!match) throw new Error(`expected an HSL channel, got ${value}`);
  const hue = Number(match[1]);
  const sat = Number(match[2]) / 100;
  const lig = Number(match[3]) / 100;
  const a = sat * Math.min(lig, 1 - lig);
  const channel = (n) => {
    const k = (n + hue / 30) % 12;
    const color = lig - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
    return Math.round(Math.min(1, Math.max(0, color)) * 255);
  };
  return `#${[channel(0), channel(8), channel(4)]
    .map((part) => part.toString(16).padStart(2, "0"))
    .join("")}`;
}

function write(name, contents) {
  writeFileSync(path.join(outDir, name), contents);
}

function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, "");
}

function rulesIn(text) {
  const found = [];
  const visit = (source) => {
    for (const rule of topLevel(source)) {
      found.push(rule);
      if (rule.selector.trim().startsWith("@")) visit(rule.body);
    }
  };
  visit(text);
  return found;
}

function topLevel(source) {
  const rules = [];
  let depth = 0;
  let start = 0;
  let selector = "";
  let bodyStart = 0;
  for (let i = 0; i < source.length; i++) {
    const char = source[i];
    if (char === "{") {
      if (depth === 0) {
        selector = source.slice(start, i);
        bodyStart = i + 1;
      }
      depth++;
    } else if (char === "}") {
      depth--;
      if (depth === 0) {
        rules.push({ selector, body: source.slice(bodyStart, i) });
        start = i + 1;
      }
    } else if (char === ";" && depth === 0) {
      start = i + 1;
    }
  }
  return rules;
}

function declarations(body) {
  let top = "";
  let depth = 0;
  for (const char of body) {
    if (char === "{") depth++;
    else if (char === "}") depth = Math.max(0, depth - 1);
    else if (depth === 0) top += char;
  }
  const entries = [];
  for (const part of top.split(";")) {
    const match = part.match(/^\s*(--[\w-]+)\s*:\s*([\s\S]+?)\s*$/);
    if (match) entries.push([match[1], match[2].replace(/\s+/g, " ")]);
  }
  return entries;
}
